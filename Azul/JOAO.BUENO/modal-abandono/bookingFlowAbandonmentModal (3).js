        function orderFlights(label = "Menor preço") {
            const ALL_OPTIONS = [
                "Mais cedo",
                "Menor preço",
                "Maior preço",
                "Mais rápido",
                "Mais tarde",
                "Voo direto",
                "Duração",
            ];

            const KEY_STEPS = {
                "Mais cedo": 0,
                "Menor preço": 1,
                "Maior preço": 2,
                "Mais rápido": 3,
                "Mais tarde": 4,
                "Voo direto": 5,
                Duração: 6,
            };

            function simulateKey(el, key) {
                const code = key === "Enter" ? 13 : 40;
                el.dispatchEvent(
                  new KeyboardEvent("keydown", {
                    key,
                    code: key,
                    keyCode: code,
                    which: code,
                    bubbles: true,
                    cancelable: true,
                  })
                );
            }

            function applyFilter(wrapper, label = "Menor preço", useSteps = false) {
                const input = wrapper.querySelector(SELECTORS.inputOrderTariffsOnFlightsStep);
                if (!input) return;
                input.focus();
                simulateKey(input, "ArrowDown");
            
                setTimeout(() => {
                    if (useSteps) {
                        const steps = KEY_STEPS[label] || 0;
                        for (let i = 0; i < steps; i++) simulateKey(input, "ArrowDown");
                    } else {
                        const current = wrapper
                        .querySelector(".css-pdoeiw-singleValue")
                        ?.textContent.trim();
                        const curIdx = ALL_OPTIONS.indexOf(current);
                        const tgtIdx = ALL_OPTIONS.indexOf(label);
                        const delta = tgtIdx - (curIdx >= 0 ? curIdx : -1);
                        const dir = delta > 0 ? "ArrowDown" : "ArrowUp";
                        for (let i = 0; i < Math.abs(delta); i++) simulateKey(input, dir);
                    }

                    simulateKey(input, "Enter");
                
                    const bar = wrapper.querySelector(".azul-sort-button-bar");
                    if (bar) {
                        bar
                        .querySelectorAll(".azul-sort-btn")
                        .forEach((b) => b.classList.remove("active"));
                        const btn = Array.from(bar.children).find(
                        (b) => b.textContent === label
                        );
                        if (btn) btn.classList.add("active");
                    }
                }, 150);
            }
            
            const inputsOrder = document.querySelector(SELECTORS.wrapperOrderTariffsOnFlightsStep);
            const currentLabel = inputsOrder.querySelector(SELECTORS.labelOrderTariffsOnFlightsStep).textContent.trim() || "";
            const useSteps = currentLabel == "Selecione" ? true : false;

            applyFilter(inputsOrder, label, useSteps);
        }

